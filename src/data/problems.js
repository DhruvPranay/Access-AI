/** Returns tests with expected outputs, computing them from the reference solver. */
const cache = new Map();
export function testsFor(problem) {
  if (problem.generated) return problem.tests; // AI problems carry outputs from the server
  if (cache.has(problem.id)) return cache.get(problem.id);
  const t = problem.tests.map((input) => ({ input, output: problem.solve(input) }));
  cache.set(problem.id, t);
  return t;
}

